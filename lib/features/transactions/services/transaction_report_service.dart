  const TransactionReportService();

  Future<void> printComparisonReport({
    required List<Transaction> firstTransactions,
    required List<Transaction> secondTransactions,
    required String firstLabel,
    required String secondLabel,
  }) async {
    await Printing.layoutPdf(
      name: 'Filer Flow Comparison Report',
      onLayout: (format) => buildComparisonReport(
        firstTransactions: firstTransactions,
        secondTransactions: secondTransactions,
        firstLabel: firstLabel,
        secondLabel: secondLabel,
        pageFormat: format,
      ),
    );
  }

  Future<Uint8List> buildComparisonReport({
    required List<Transaction> firstTransactions,
    required List<Transaction> secondTransactions,
    required String firstLabel,
    required String secondLabel,
    PdfPageFormat pageFormat = PdfPageFormat.a4,
  }) async {
    final first = _ReportPeriodTotals.from(firstTransactions);
    final second = _ReportPeriodTotals.from(secondTransactions);
    final incomeDifference = second.income - first.income;
    final expenseDifference = second.expenses - first.expenses;
    final balanceDifference = second.balance - first.balance;
    final generatedAt = DateFormat(
      'dd MMM yyyy, h:mm a',
    ).format(DateTime.now());
    final pdf = pw.Document(
      title: 'Filer Flow Comparison Report',
      author: 'Filer Flow',
      subject: '$firstLabel compared with $secondLabel',
    );

    pdf.addPage(
      pw.MultiPage(
        pageTheme: pw.PageTheme(
          pageFormat: pageFormat,
          margin: const pw.EdgeInsets.all(32),
        ),
        footer: (context) => pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              'Generated by Filer Flow',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
            ),
            pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount}',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
            ),
          ],
        ),
        build: (context) => [
          pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.all(20),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromHex('#0F6B57'),
              borderRadius: pw.BorderRadius.circular(12),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  'Filer Flow',
                  style: pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 24,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.SizedBox(height: 4),
                pw.Text(
                  'Comparison Report',
                  style: const pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 16,
                  ),
                ),
                pw.SizedBox(height: 10),
                pw.Text(
                  '$firstLabel compared with $secondLabel',
                  style: const pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 11,
                  ),
                ),
                pw.Text(
                  'Generated: $generatedAt',
                  style: const pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 9,
                  ),
                ),
              ],
            ),
          ),
          pw.SizedBox(height: 20),
          pw.Row(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Expanded(child: _comparisonPeriodCard(firstLabel, first)),
              pw.SizedBox(width: 12),
              pw.Expanded(child: _comparisonPeriodCard(secondLabel, second)),
            ],
          ),
          pw.SizedBox(height: 18),
          pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.all(16),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromHex('#E7F0EA'),
              borderRadius: pw.BorderRadius.circular(10),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.stretch,
              children: [
                pw.Text(
                  'Difference ($secondLabel - $firstLabel)',
                  style: pw.TextStyle(
                    fontSize: 15,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColor.fromHex('#123D36'),
                  ),
                ),
                pw.SizedBox(height: 10),
                _totalRow(
                  'Income difference',
                  _formatSignedMoney(incomeDifference),
                ),
                _totalRow(
                  'Expense difference',
                  _formatSignedMoney(expenseDifference),
                ),
                pw.Divider(color: PdfColors.grey400),
                _totalRow(
                  'Net Balance difference',
                  _formatSignedMoney(balanceDifference),
                  emphasize: true,
                ),
              ],
            ),
          ),
        ],
      ),
    );
    return pdf.save();
  }

  Future<void> printReport({
    required List<Transaction> transactions,
    required String filterLabel,
  }) async {
    await Printing.layoutPdf(
      name: 'Filer Flow Transaction Report',
      onLayout: (format) => buildReport(
        transactions: transactions,
        filterLabel: filterLabel,
        pageFormat: format,
      ),
    );
  }

  Future<void> printFinancialReport({
    required List<Transaction> periodTransactions,
    required List<Transaction> allTransactions,
    required List<Asset> assets,
    required List<KhataEntry> khataEntries,
    required String periodLabel,
  }) async {
    await Printing.layoutPdf(
      name: 'Filer Flow Financial Report',
      onLayout: (format) => buildFinancialReport(
        periodTransactions: periodTransactions,
        allTransactions: allTransactions,
        assets: assets,
        khataEntries: khataEntries,
        periodLabel: periodLabel,
        pageFormat: format,
      ),
    );
  }

  Future<Uint8List> buildFinancialReport({
    required List<Transaction> periodTransactions,
    required List<Transaction> allTransactions,
    required List<Asset> assets,
    required List<KhataEntry> khataEntries,
    required String periodLabel,
    PdfPageFormat pageFormat = PdfPageFormat.a4,
  }) async {
    final generatedAt = DateTime.now();
    final currentDate = DateFormat('dd MMM yyyy').format(generatedAt);
    final allIncome = allTransactions
        .where((transaction) => !transaction.isExpense)
        .fold<double>(0, (sum, transaction) => sum + transaction.amount);
    final allExpenses = allTransactions
        .where((transaction) => transaction.isExpense)
        .fold<double>(0, (sum, transaction) => sum + transaction.amount);
    final cash = allIncome - allExpenses;
    final assetsTotal = assets.fold<double>(
      0,
      (sum, asset) => sum + asset.value,
    );
    final receivables = khataEntries
        .where(
          (entry) => !entry.isPayable && !entry.isPaid && !entry.isWrittenOff,
        )
        .fold<double>(0, (sum, entry) => sum + entry.remainingAmount);
    final payables = khataEntries
        .where(
          (entry) => entry.isPayable && !entry.isPaid && !entry.isWrittenOff,
        )
        .fold<double>(0, (sum, entry) => sum + entry.remainingAmount);
    final netWorth = cash + assetsTotal + receivables - payables;
    final periodIncome = periodTransactions
        .where((transaction) => !transaction.isExpense)
        .fold<double>(0, (sum, transaction) => sum + transaction.amount);
    final periodExpenses = periodTransactions
        .where((transaction) => transaction.isExpense)
        .fold<double>(0, (sum, transaction) => sum + transaction.amount);
    final pdf = pw.Document(
      title: 'Filer Flow Financial Report',
      author: 'Filer Flow',
      subject: periodLabel,
    );

    pdf.addPage(
      pw.MultiPage(
        pageTheme: pw.PageTheme(
          pageFormat: pageFormat,
          margin: const pw.EdgeInsets.all(32),
        ),
        footer: (context) => _reportFooter(context),
        build: (context) => [
          _buildFinancialHeader(periodLabel, generatedAt),
          pw.SizedBox(height: 18),
          _financialSectionTitle('Net Worth Summary (as of $currentDate)'),
          _financialSummaryGrid([
            ('Cash', _formatMoney(cash)),
            ('Total assets', _formatMoney(assetsTotal)),
            ('Receivables', _formatMoney(receivables)),
            ('Payables', _formatMoney(payables)),
            ('Total net worth', _formatMoney(netWorth)),
          ]),
          pw.SizedBox(height: 18),
          _financialSectionTitle('Assets Breakdown (as of $currentDate)'),
          _buildAssetsSection(assets),
          pw.SizedBox(height: 18),
          _financialSectionTitle('Khata Breakdown (current open balances)'),
          _buildKhataSection(khataEntries),
          pw.SizedBox(height: 18),
          _financialSectionTitle('Income & Expense Summary ($periodLabel)'),
          _buildSummary(income: periodIncome, expenses: periodExpenses),
          pw.SizedBox(height: 18),
          _financialSectionTitle('Top Categories ($periodLabel)'),
          _buildTopCategoryCards(periodTransactions),
        ],
      ),
    );
    return pdf.save();
  }

  Future<Uint8List> buildReport({
    required List<Transaction> transactions,
    required String filterLabel,
    PdfPageFormat pageFormat = PdfPageFormat.a4,
  }) async {
    final pdf = pw.Document(
      title: 'Filer Flow Transaction Report',
      author: 'Filer Flow',
      subject: filterLabel,
    );
    final receiptImages = <int, pw.MemoryImage>{};
    for (var index = 0; index < transactions.length; index++) {
      final imagePath = transactions[index].receiptImagePath;
      if (imagePath == null || imagePath.isEmpty) continue;
      try {
        final file = File(imagePath);
        if (await file.exists()) {
          receiptImages[index] = pw.MemoryImage(await file.readAsBytes());
        }
      } on FileSystemException {
        // A missing or unreadable attachment should not block the report.
      }
    }

    final income = transactions
        .where((transaction) => !transaction.isExpense)
        .fold<double>(0, (sum, transaction) => sum + transaction.amount);
    final expenses = transactions
        .where((transaction) => transaction.isExpense)
        .fold<double>(0, (sum, transaction) => sum + transaction.amount);
    final generatedAt = DateFormat(
      'dd MMM yyyy, h:mm a',
    ).format(DateTime.now());

    pdf.addPage(
      pw.MultiPage(
        pageTheme: pw.PageTheme(
          pageFormat: pageFormat,
          margin: const pw.EdgeInsets.all(32),
        ),
        footer: (context) => pw.Container(
          padding: const pw.EdgeInsets.only(top: 8),
          decoration: const pw.BoxDecoration(
            border: pw.Border(top: pw.BorderSide(color: PdfColors.grey300)),
          ),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                'Generated by Filer Flow',
                style: const pw.TextStyle(
                  fontSize: 9,
                  color: PdfColors.grey600,
                ),
              ),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: const pw.TextStyle(
                  fontSize: 9,
                  color: PdfColors.grey600,
                ),
              ),
            ],
          ),
        ),
        build: (context) => [
          _buildHeader(filterLabel, generatedAt),
          pw.SizedBox(height: 18),
          _buildSummary(income: income, expenses: expenses),
          pw.SizedBox(height: 20),
          pw.Text(
            'Transaction details',
            style: pw.TextStyle(
              fontSize: 17,
              fontWeight: pw.FontWeight.bold,
              color: PdfColor.fromHex('#123D36'),
            ),
          ),
          pw.SizedBox(height: 10),
          if (transactions.isEmpty)
            pw.Container(
              width: double.infinity,
              padding: const pw.EdgeInsets.all(20),
              decoration: pw.BoxDecoration(
                color: PdfColor.fromHex('#F6F7F4'),
                borderRadius: pw.BorderRadius.circular(8),
              ),
              child: pw.Text(
                'No transactions match this filter.',
                textAlign: pw.TextAlign.center,
              ),
            )
          else
            for (var index = 0; index < transactions.length; index++) ...[
              _buildTransaction(
                transactions[index],
                receiptImage: receiptImages[index],
              ),
              pw.SizedBox(height: 10),
            ],
          pw.SizedBox(height: 12),
          _buildReportTotals(income: income, expenses: expenses),
        ],
      ),
    );
    return pdf.save();
  }

