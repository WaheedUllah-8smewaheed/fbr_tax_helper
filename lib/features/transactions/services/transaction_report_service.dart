  }

  pw.Widget _buildAssetsSection(List<Asset> assets) {
    if (assets.isEmpty) return _emptyReportSection('None');
    return pw.Table(
      border: pw.TableBorder.all(color: PdfColors.grey300),
      columnWidths: const {
        0: pw.FlexColumnWidth(2),
        1: pw.FlexColumnWidth(1),
        2: pw.FlexColumnWidth(1),
      },
      children: [
        _tableHeader(['Asset', 'Category', 'Current value']),
        ...assets.map(
          (asset) => _tableRow([
            asset.name,
            asset.category.displayName,
            _formatMoney(asset.value),
          ]),
        ),
      ],
    );
  }

  pw.Widget _buildTopCategoryCards(List<Transaction> transactions) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Expanded(
          child: _buildTopCategoryCard(
            title: 'Top 5 Income',
            color: '#0F6B57',
            totals: _topCategoryTotals(transactions, isExpense: false),
          ),
        ),
        pw.SizedBox(width: 10),
        pw.Expanded(
          child: _buildTopCategoryCard(
            title: 'Top 5 Expenses',
            color: '#B3261E',
            totals: _topCategoryTotals(transactions, isExpense: true),
          ),
        ),
      ],
    );
  }

  List<MapEntry<String, double>> _topCategoryTotals(
    List<Transaction> transactions, {
    required bool isExpense,
  }) {
    final totals = <String, double>{};
    for (final transaction in transactions) {
      if (transaction.isExpense != isExpense) continue;
      totals.update(
        transaction.category,
        (value) => value + transaction.amount,
        ifAbsent: () => transaction.amount,
      );
    }
    return totals.entries.toList()
      ..sort((first, second) => second.value.compareTo(first.value));
  }

  pw.Widget _buildTopCategoryCard({
    required String title,
    required String color,
    required List<MapEntry<String, double>> totals,
  }) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        color: PdfColor.fromHex('#F6F7F4'),
        border: pw.Border.all(color: PdfColor.fromHex('#B7C9C3')),
        borderRadius: pw.BorderRadius.circular(8),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.stretch,
        children: [
          pw.Text(
            title,
            style: pw.TextStyle(
              fontSize: 12,
              fontWeight: pw.FontWeight.bold,
              color: PdfColor.fromHex(color),
            ),
          ),
          pw.SizedBox(height: 6),
          if (totals.isEmpty)
            pw.Text('None', style: const pw.TextStyle(fontSize: 9))
          else
            for (final category in totals.take(5))
              pw.Padding(
                padding: const pw.EdgeInsets.symmetric(vertical: 3),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Expanded(
                      child: pw.Text(
                        category.key,
                        style: const pw.TextStyle(fontSize: 9),
                      ),
                    ),
                    pw.Text(
                      _formatMoney(category.value),
                      style: pw.TextStyle(
                        fontSize: 9,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColor.fromHex(color),
                      ),
                    ),
                  ],
                ),
              ),
        ],
      ),
    );
  }

  pw.Widget _buildKhataSection(List<KhataEntry> entries) {
    final payables = entries
        .where(
          (entry) => entry.isPayable && !entry.isPaid && !entry.isWrittenOff,
        )
        .toList();
    final receivables = entries
        .where(
          (entry) => !entry.isPayable && !entry.isPaid && !entry.isWrittenOff,
        )
        .toList();
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.stretch,
      children: [
        pw.Text(
          'Open Payables',
          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
        ),
        _buildKhataTable(payables),
        pw.SizedBox(height: 10),
        pw.Text(
          'Open Receivables',
          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
        ),
        _buildKhataTable(receivables),
      ],
    );
  }

  pw.Widget _buildKhataTable(List<KhataEntry> entries) {
    if (entries.isEmpty) return _emptyReportSection('None');
    return pw.Table(
      border: pw.TableBorder.all(color: PdfColors.grey300),
      children: [
        _tableHeader(['Counterparty', 'Amount', 'Due date', 'Status']),
        ...entries.map((entry) {
          final dueDate = entry.dueDate;
          final overdue = dueDate != null && dueDate.isBefore(DateTime.now());
          final dueText = dueDate == null
              ? 'Not set'
              : DateFormat('dd MMM yyyy').format(dueDate);
          return _tableRow([
            entry.party,
            _formatMoney(entry.remainingAmount),
            dueText,
            overdue
                ? '${DateTime.now().difference(dueDate).inDays} days overdue'
                : 'Open',
          ]);
        }),
      ],
    );
  }

  pw.TableRow _tableHeader(List<String> values) {
    return pw.TableRow(
      decoration: pw.BoxDecoration(color: PdfColor.fromHex('#B5D7CA')),
      children: values
          .map(
            (value) => pw.Padding(
              padding: const pw.EdgeInsets.all(6),
              child: pw.Text(
                value,
                style: pw.TextStyle(
                  fontWeight: pw.FontWeight.bold,
                  fontSize: 9,
                ),
              ),
            ),
          )
          .toList(),
    );
  }

  pw.TableRow _tableRow(List<String> values) {
    return pw.TableRow(
      decoration: pw.BoxDecoration(color: PdfColors.white),
      children: values
          .map(
            (value) => pw.Padding(
              padding: const pw.EdgeInsets.all(6),
              child: pw.Text(value, style: const pw.TextStyle(fontSize: 9)),
            ),
          )
          .toList(),
    );
  }

