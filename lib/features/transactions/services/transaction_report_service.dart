        pw.SizedBox(width: 8),
        pw.Expanded(child: _summaryCell('Expenses', _formatMoney(expenses))),
        pw.SizedBox(width: 8),
        pw.Expanded(
          child: _summaryCell('Balance', _formatMoney(income - expenses)),
        ),
      ],
    );
  }

